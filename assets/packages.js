/* ── 화면별 뷰 - 같은 시드에서 파생 ───────────────────── */

/* 분류명이 이름에 없으면 앞에 붙인다 - 좌측바나 목록을 안 봐도 무엇의 패키지인지 읽혀야 한다 */
function pkgFullName(row, catName){
  return row.nm.includes(catName) ? row.nm : `${catName} ${row.nm}`;
}

/* 수강신청 화면 - 관리자 목록 형태 [분류, 이름, 과목수, 판매가, 교차] */
function pkgAdminRows(){
  return PKG_SEED.map(r => [r.pcat, r.nm, r.n, r.price, r.cross]);
}

/* 제안 화면 - 노출번호(슬롯)별 상품. cls는 PKG_CLS의 키 */
function pkgSlots(){
  const out = {};
  Object.keys(PKG_CLS).forEach(cls => {
    const cat = PKG_CLS[cls];
    out[cls] = {};
    PKG_SEED.filter(r => r.pcat===cat.pcat && r.no).forEach(r => {
      out[cls][r.no] = {
        nm: pkgFullName(r, cat.nm), compo: r.compo, n: r.n,
        key: r.key, region: r.region,
        /* 목록 과목수와 상세 구성 과목수가 다르면 담당자 화면에 그대로 드러낸다 */
        nDetail: (PKG_COMPO[r.key]||[]).reduce((t,g)=>t+g.s.length, 0),
      };
    });
  });
  return out;
}

/* 제안 화면 - 패키지 레코드(분류 × 슬롯 × 차수) 평면화 */
function pkgRounds(){
  const out = [];
  Object.keys(PKG_CLS).forEach(cls => {
    const cat = PKG_CLS[cls];
    PKG_SEED.filter(r => r.pcat===cat.pcat && r.no && r.rounds).forEach(r => {
      r.rounds.forEach(b => out.push({
        id:b.id, cls, no:r.no, batch:b.batch, apply:b.apply, status:b.status, opens:b.opens
      }));
    });
  });
  return out;
}
